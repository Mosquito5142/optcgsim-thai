// ==UserScript==
// @name         OPlayTCG ภาษาไทย (แปลสกิลบนการ์ด)
// @namespace    https://github.com/Mosquito5142/optcgsim-thai
// @version      0.2.261022.1007
// @description  แปลข้อความสกิลบนการ์ดใหญ่ของ oplaytcg.com เป็นภาษาไทย (กล่องข้อความไทยทับบนการ์ด เหมือนม็อด OPTCGSim) ม็อดแฟนเมด ไม่เป็นทางการ แปลโดย $ong$oul กด Alt+T เปิด/ปิด
// @author       $ong$oul
// @match        https://oplaytcg.com/*
// @match        https://www.oplaytcg.com/*
// @require      https://raw.githubusercontent.com/Mosquito5142/optcgsim-thai/main/public/oplay/oplaytcg-thai.data.js?v=0.2.261022.1007
// @updateURL    https://raw.githubusercontent.com/Mosquito5142/optcgsim-thai/main/public/oplay/oplaytcg-thai.meta.js
// @downloadURL  https://raw.githubusercontent.com/Mosquito5142/optcgsim-thai/main/public/oplay/oplaytcg-thai.user.js
// @grant        none
// @run-at       document-idle
// ==/UserScript==

(function () {
  "use strict";
  // OPLAY_TH_DATA comes from the @require'd oplaytcg-thai.data.js (generated by build_oplay.py):
  // {styles: [[bg, fg]...], layout: {Type|id: [x1, y1, x2, y2]}, cards: {id: {n, t, y?, a: [[chips, parts, trigger?]...]}}}
  // Layout numbers are in "standard card pixels" (480 x 671), the same ones the OPTCGSim card renderer uses.
  // (assigned on globalThis so it is visible however the userscript manager scopes @require)
  const DATA = globalThis.OPLAY_TH_DATA || null;

  const store = {
    get: (k, d) => { try { const v = localStorage.getItem(k); return v === null ? d : v === "1"; } catch (_) { return d; } },
    set: (k, v) => { try { localStorage.setItem(k, v ? "1" : "0"); } catch (_) { /* storage blocked */ } },
  };
  let enabled = store.get("oplayThai.enabled", true) && Boolean(DATA);
  let popupOn = store.get("oplayThai.popup", false); // small hover popup, for cards too small to carry the overlay

  const ID_RE = /([A-Za-z0-9]+-\d{3})[^/]*\.webp/;
  const CARD_IMG = 'img[src*="cards.oplaytcg.com"]';
  const STD_W = 480, STD_H = 671;
  const MIN_OVERLAY_W = 200; // card images narrower than this (thumbnails) get no overlay
  const FONT = '"Leelawadee UI","Noto Sans Thai","Sarabun",Tahoma,sans-serif';
  const CREDIT = "แปลไทยโดย $ong$oul";

  const style = document.createElement("style");
  style.textContent = `
    .oplay-th-ov{position:fixed;left:0;top:0;width:${STD_W}px;height:${STD_H}px;transform-origin:0 0;pointer-events:none;
      z-index:2147483000;font-family:${FONT};}
    .oplay-th-ov *{box-sizing:border-box}
    .oplay-th-ov .box{position:absolute;background:#f3eedc;border-radius:6px;color:#231f20;overflow:hidden}
    .oplay-th-ov .main{position:absolute;left:8px;right:8px;top:8px;overflow:hidden}
    .oplay-th-ov .bar{position:absolute;left:4px;right:4px;bottom:4px;background:#231f20;color:#fff;border-radius:6px;padding:3px 4px 3px 4px}
    .oplay-th-ov p{margin:0}
    .oplay-th-ov p + p{margin-top:4px}
    .oplay-th-ov .c{display:inline-block;padding:0 5px;border-radius:999px;font-weight:700;line-height:1.3;white-space:nowrap}
    .oplay-th-ov .cr{position:absolute;right:8px;font-size:10px;color:#8c8674;line-height:1.45}
    #oplay-th-tip{position:fixed;z-index:2147483647;max-width:min(340px,92vw);padding:12px 14px;border-radius:12px;
      background:#141a26;color:#eef1f7;border:1px solid #3a4560;box-shadow:0 12px 32px rgba(0,0,0,.55);
      font:14px/1.7 ${FONT};pointer-events:none;display:none}
    #oplay-th-tip .h{font-size:12px;color:#9fb0cf;margin-bottom:6px}
    #oplay-th-tip .a{margin:0 0 8px}
    #oplay-th-tip .a:last-of-type{margin-bottom:0}
    #oplay-th-tip .c{display:inline-block;padding:0 8px;margin:0 2px;border-radius:999px;font-weight:700;font-size:12.5px;line-height:1.55}
    #oplay-th-tip .f{margin-top:8px;font-size:11px;color:#7d8aa6;text-align:right}
    #oplay-th-toast{position:fixed;left:50%;bottom:24px;transform:translateX(-50%);z-index:2147483647;padding:8px 16px;
      border-radius:999px;background:#141a26;color:#eef1f7;border:1px solid #3a4560;font:13px ${FONT};
      pointer-events:none;opacity:0;transition:opacity .2s}`;
  document.head.appendChild(style);

  function chipEl(c) {
    const s = document.createElement("span");
    s.className = "c";
    s.textContent = c[0];
    const [bg, fg] = DATA.styles[c[1]];
    s.style.background = bg;
    s.style.color = fg;
    return s;
  }

  function idOf(img) {
    const m = ID_RE.exec(img.currentSrc || img.src);
    return m && m[1].toUpperCase();
  }

  // ---------- overlay on the big card ----------

  /** One ability as a paragraph: keyword pills first, then the Thai sentences (pills inside sentences are chips too). */
  function paragraph(ability) {
    const p = document.createElement("p");
    for (const c of ability[0]) { p.appendChild(chipEl(c)); p.appendChild(document.createTextNode(" ")); }
    for (const part of ability[1]) p.appendChild(typeof part === "string" ? document.createTextNode(part) : chipEl(part));
    return p;
  }

  /** The cream text box in standard card pixels (480x671); the whole thing is scaled to the card's on-screen size later. */
  function buildOverlay(id, card) {
    const box = DATA.layout[id] || DATA.layout[card.t];
    if (!box) return null;
    const [x1, , x2, y2] = box;
    const y1 = card.y != null ? card.y : box[1];
    const root = document.createElement("div");
    root.className = "oplay-th-ov";
    root.lang = "th";
    const boxEl = document.createElement("div");
    boxEl.className = "box";
    Object.assign(boxEl.style, { left: x1 + "px", top: y1 + "px", width: x2 - x1 + "px", height: y2 - y1 + "px" });
    root.appendChild(boxEl);
    document.body.appendChild(root); // must be in the page to measure the text

    const trig = card.a.filter((a) => a[2]);
    const main = card.a.filter((a) => !a[2]);
    let bottom = 8;
    if (trig.length) {
      const bar = document.createElement("div");
      bar.className = "bar";
      for (const a of trig) bar.appendChild(paragraph(a));
      boxEl.appendChild(bar);
      for (let size = 14; size >= 11; size--) {
        bar.style.fontSize = size + "px";
        bar.style.lineHeight = "1.45";
        if (bar.offsetHeight <= 66) break;
      }
      bottom = bar.offsetHeight + 8;
    }
    const mainEl = document.createElement("div");
    mainEl.className = "main";
    mainEl.style.bottom = bottom + "px";
    for (const a of main) mainEl.appendChild(paragraph(a));
    boxEl.appendChild(mainEl);
    for (let size = 17; size >= 11; size--) {
      mainEl.style.fontSize = size + "px";
      mainEl.style.lineHeight = "1.45";
      if (mainEl.scrollHeight <= mainEl.clientHeight) break;
    }
    // translator credit in the free corner, only when a whole free line is left
    if (mainEl.clientHeight - mainEl.scrollHeight >= 15) {
      const cr = document.createElement("div");
      cr.className = "cr";
      cr.textContent = CREDIT;
      cr.style.bottom = bottom - 2 + "px";
      boxEl.appendChild(cr);
    }
    return root;
  }

  const overlays = new Map(); // card <img> -> {id, el}

  function removeOverlay(img) {
    const o = overlays.get(img);
    if (o && o.el) o.el.remove();
    overlays.delete(img);
  }

  function syncOverlays() {
    const live = new Set();
    if (enabled) {
      for (const img of document.querySelectorAll(CARD_IMG)) {
        const r = img.getBoundingClientRect();
        if (r.width < MIN_OVERLAY_W || r.height < MIN_OVERLAY_W * 1.2 || !img.complete || !img.naturalWidth) continue;
        const id = idOf(img);
        const card = id && DATA.cards[id];
        if (!card) continue;
        live.add(img);
        let o = overlays.get(img);
        if (!o || o.id !== id) {
          if (o) removeOverlay(img);
          o = { id, el: buildOverlay(id, card) };
          overlays.set(img, o);
        }
        if (!o.el) continue;
        const cs = getComputedStyle(img);
        o.el.style.transform = `translate(${r.left}px,${r.top}px) scale(${r.width / STD_W},${r.height / STD_H})`;
        o.el.style.opacity = cs.visibility === "hidden" ? "0" : cs.opacity;
      }
    }
    for (const img of [...overlays.keys()]) if (!live.has(img)) removeOverlay(img);
  }

  // rAF while an overlay is up (to follow the preview as it moves/fades), a slow poll otherwise
  function loop() {
    syncOverlays();
    if (overlays.size) requestAnimationFrame(loop);
    else setTimeout(() => requestAnimationFrame(loop), 120);
  }

  // ---------- small hover popup (optional, Alt+P) ----------

  const tip = document.createElement("div");
  tip.id = "oplay-th-tip";
  document.body.appendChild(tip);

  function fillTip(id, card) {
    tip.textContent = "";
    const h = document.createElement("div");
    h.className = "h";
    h.textContent = card.n ? `${id} · ${card.n}` : id;
    tip.appendChild(h);
    for (const [chips, parts] of card.a) {
      const p = document.createElement("div");
      p.className = "a";
      for (const c of chips) p.appendChild(chipEl(c));
      if (chips.length) p.appendChild(document.createTextNode(" "));
      for (const part of parts) p.appendChild(typeof part === "string" ? document.createTextNode(part) : chipEl(part));
      tip.appendChild(p);
    }
    const f = document.createElement("div");
    f.className = "f";
    f.textContent = CREDIT + " · ไม่เป็นทางการ";
    tip.appendChild(f);
  }

  /** Topmost card image under the pointer. elementsFromPoint sees through the transparent hit-layers and overlays the site stacks on cards. */
  function cardAt(x, y) {
    for (const el of document.elementsFromPoint(x, y)) {
      if (el.tagName === "IMG" && el.matches(CARD_IMG)) return el;
    }
    return null;
  }

  let current = null;
  let mouse = { x: 0, y: 0 };
  let raf = 0;

  function placeTip() {
    const pad = 16, w = tip.offsetWidth, h = tip.offsetHeight;
    let x = mouse.x + pad, y = mouse.y + pad;
    if (x + w > innerWidth - 8) x = mouse.x - w - pad;
    if (y + h > innerHeight - 8) y = innerHeight - h - 8;
    tip.style.left = Math.max(8, x) + "px";
    tip.style.top = Math.max(8, y) + "px";
  }

  function hideTip() {
    current = null;
    tip.style.display = "none";
  }

  function showTip(img) {
    const id = idOf(img);
    const card = id && DATA.cards[id];
    if (!card) return hideTip();
    if (current !== img) {
      current = img;
      fillTip(id, card);
    }
    tip.style.display = "block";
    placeTip();
  }

  function tick() {
    raf = 0;
    if (!enabled || !popupOn) return hideTip();
    const img = cardAt(mouse.x, mouse.y);
    if (img) showTip(img); else if (current) hideTip();
  }

  document.addEventListener("mousemove", (e) => {
    if (!popupOn) return;
    mouse = { x: e.clientX, y: e.clientY };
    if (!raf) raf = requestAnimationFrame(tick);
  }, true);
  document.documentElement.addEventListener("mouseleave", hideTip);
  window.addEventListener("scroll", hideTip, true);
  window.addEventListener("blur", hideTip);

  // ---------- toast + keys ----------

  function toast(msg) {
    let t = document.getElementById("oplay-th-toast");
    if (!t) { t = document.createElement("div"); t.id = "oplay-th-toast"; document.body.appendChild(t); }
    t.textContent = msg;
    t.style.opacity = "1";
    clearTimeout(toast.timer);
    toast.timer = setTimeout(() => { t.style.opacity = "0"; }, 2200);
  }

  document.addEventListener("keydown", (e) => {
    if (!e.altKey || e.ctrlKey || e.metaKey) return;
    const k = e.key.toLowerCase();
    if (k === "t" && DATA) {
      enabled = !enabled;
      store.set("oplayThai.enabled", enabled);
      if (!enabled) hideTip();
      toast(enabled ? "OPlay ไทย: เปิด (Alt+T เพื่อปิด)" : "OPlay ไทย: ปิด (Alt+T เพื่อเปิด)");
    } else if (k === "p" && DATA) {
      popupOn = !popupOn;
      store.set("oplayThai.popup", popupOn);
      if (!popupOn) hideTip();
      toast(popupOn ? "ป๊อปอัปข้างเมาส์: เปิด (Alt+P เพื่อปิด)" : "ป๊อปอัปข้างเมาส์: ปิด (Alt+P เพื่อเปิด)");
    }
  });

  // Startup check: one short toast per tab session so players can see the script is alive (or why not).
  try {
    if (!sessionStorage.getItem("oplayThai.hello")) {
      sessionStorage.setItem("oplayThai.hello", "1");
      toast(DATA ? `OPlay ไทย พร้อมใช้งาน (${Object.keys(DATA.cards).length} การ์ด) · ชี้การ์ดใหญ่ · Alt+T เปิด/ปิด` : "OPlay ไทย: โหลดข้อมูลคำแปลไม่สำเร็จ ลองรีเฟรชหน้า");
    }
  } catch (_) { /* storage blocked */ }
  console.info("[OPlay ไทย]", DATA ? `loaded ${Object.keys(DATA.cards).length} cards` : "data missing");

  if (DATA) loop();
})();
